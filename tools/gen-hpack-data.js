// One-off generator for lib/hpack-data.js.
// Extracts both normative HPACK tables (RFC 7541 App. A + B) from nghttp2's
// generated C sources so we transcribe nothing by hand.
//   node tools/gen-hpack-data.js <nghttp2_hd_huffman_data.c> <nghttp2_hd.c>
const fs = require('node:fs');

// ---------- RFC 7541 Appendix B: Huffman code table ----------
const huffSrc = fs.readFileSync(process.argv[2], 'utf8');
const huffBody = /huff_sym_table\[\]\s*=\s*\{([\s\S]*?)\};/.exec(huffSrc)[1];

const sym = [];
for (const m of huffBody.matchAll(/\{\s*(\d+)\s*,\s*(0x[0-9A-Fa-f]+)U?\s*\}/g)) {
  const bits = Number(m[1]);
  // nghttp2 stores codes left-aligned in 32 bits; recover the plain value
  sym.push([bits, Number(BigInt(m[2]) >> BigInt(32 - bits))]);
}
if (sym.length !== 257) {
  throw new Error(`huffman: expected 257 entries, got ${sym.length}`);
}
const HUFF_BITS = sym.map((e) => e[0]);
const HUFF_CODES = sym.map((e) => e[1]);

// normative property of the code: prefix-free, lengths 5..30, EOS = 30 bits
for (let i = 0; i < 257; i++) {
  for (let j = 0; j < 257; j++) {
    if (i === j || HUFF_BITS[j] > HUFF_BITS[i]) {
      continue;
    }
    if ((HUFF_CODES[i] >>> (HUFF_BITS[i] - HUFF_BITS[j])) === HUFF_CODES[j]) {
      throw new Error(`huffman: sym ${i} is prefixed by sym ${j}`);
    }
  }
}
const minBits = Math.min(...HUFF_BITS.slice(0, 256));
if (Math.max(...HUFF_BITS) !== 30 || minBits !== 5 || HUFF_BITS[256] !== 30) {
  throw new Error(`huffman: unexpected bit range ${minBits}..${Math.max(...HUFF_BITS)}`);
}
// known shortest code belongs to 'e' (5 bits) -- guards against a shifted table
if (HUFF_BITS[0x65] !== 5) {
  throw new Error('huffman: \'e\' is not 5 bits, table misaligned');
}

// ---------- RFC 7541 Appendix A: static table ----------
const hdSrc = fs.readFileSync(process.argv[3], 'utf8');
const entries = [];
const block = /static const nghttp2_hd_entry static_entry_table\[\] = \{([\s\S]*?)\n\};/.exec(hdSrc);
const source = block ? block[1] : hdSrc;
for (const m of source.matchAll(/MAKE_STATIC_ENT\(\s*("(?:[^"\\]|\\.)*")\s*,\s*("(?:[^"\\]|\\.)*")/g)) {
  entries.push([JSON.parse(m[1]), JSON.parse(m[2])]);
}
if (entries.length !== 61) {
  throw new Error(`static table: expected 61 entries, got ${entries.length}`);
}
// spot-check the well-known anchors: index 2 = :method GET, 8 = :status 200
const expect = (i, n, v) => {
  if (entries[i][0] !== n || entries[i][1] !== v) {
    throw new Error(`static[${i + 1}]: got ${JSON.stringify(entries[i])}, want ${n}=${v}`);
  }
};
expect(1, ':method', 'GET');
expect(7, ':status', '200');
expect(15, 'accept-encoding', 'gzip, deflate');
expect(27, 'content-length', '');
expect(30, 'content-type', '');
expect(53, 'server', '');
expect(54, 'set-cookie', '');
expect(57, 'user-agent', '');
expect(60, 'www-authenticate', '');

const q = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

const out = `// GENERATED by tools/gen-hpack-data.js -- do not edit.
// RFC 7541 Appendix A (static table) and Appendix B (Huffman codes), transcribed
// mechanically from nghttp2's generated C tables (MIT, (c) Tatsuhiro Tsujikawa).
'use strict';

const STATIC = [
${entries.map(([n, v]) => `  [${q(n)}, ${q(v)}],`).join('\n')}
];

// index 0..255 = octet, 256 = EOS
const HUFF_BITS = new Uint8Array([${HUFF_BITS.join(',')}]);

const HUFF_CODES = new Uint32Array([
${HUFF_CODES.map((c) => `  0x${c.toString(16)},`).join('\n')}
]);

module.exports = { STATIC, HUFF_BITS, HUFF_CODES };
`;
fs.writeFileSync(`${__dirname}/../lib/hpack-data.js`, out);
console.log(`ok: huffman 257 entries (prefix-free, ${minBits}..30 bits), static table ${entries.length} entries`);
